#!/usr/bin/env bash
# Generates pydantic models from generated/openapi/reports-py.json, the way
# oapi-codegen serves the Go service. With --check, fails if the checked-in models
# are stale instead of writing them.
#
# Models ignore unknown fields (--extra-fields ignore). Closed request objects are
# enforced by validating requests against the OpenAPI document (contract.py), and
# event consumers must ignore fields they do not know (docs/stability.md).
set -euo pipefail

cd "$(dirname "$0")/.."
target=src/modura_reports/models.py
out="$target"
if [ "${1:-}" = "--check" ]; then
  tmpdir="$(mktemp -d "${TMPDIR:-/tmp}/modura-models.XXXXXX")"
  out="$tmpdir/models.py"
  trap 'rm -rf "$tmpdir"' EXIT
fi

uv run --quiet datamodel-codegen \
  --input ../../generated/openapi/reports-py.json \
  --input-file-type openapi \
  --output "$out" \
  --output-model-type pydantic_v2.BaseModel \
  --target-python-version 3.13 \
  --use-standard-collections \
  --use-union-operator \
  --use-annotated \
  --field-constraints \
  --disable-timestamp \
  --extra-fields ignore \
  --formatters builtin \
  --custom-file-header "# Generated by scripts/generate-models.sh from generated/openapi/reports-py.json. Do not edit."

if [ "$out" != "$target" ]; then
  if ! cmp -s "$out" "$target"; then
    echo "apps/reports-py/$target is stale. Run \`pnpm generate\` and commit the result." >&2
    exit 1
  fi
  echo "apps/reports-py/$target is up to date."
fi
